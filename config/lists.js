function parse(raw) {
  return raw.split('\n').map(l => l.trim()).filter(Boolean).map(l => {
    const parts = l.includes('\t') ? l.split('\t') : l.split(' | ');
    const en = parts[0].trim();
    const es = (parts[1] ?? parts[0]).trim();
    return { en, es };
  });
}
